create table usuarios (
    id bigint generated by default as identity primary key,
    login varchar(80) not null unique,
    senha varchar(100) not null,
    nome varchar(120) not null,
    perfil varchar(20) not null
);

create table clientes (
    id bigint primary key references usuarios(id) on delete cascade,
    rg varchar(20) not null,
    cpf varchar(14) not null unique,
    profissao varchar(80),
    logradouro varchar(120),
    numero varchar(10),
    bairro varchar(80),
    cidade varchar(80),
    uf varchar(2),
    cep varchar(9)
);

create table rendimentos (
    id bigint generated by default as identity primary key,
    cliente_id bigint not null references clientes(id) on delete cascade,
    entidade_empregadora varchar(120) not null,
    valor numeric(12,2) not null
);

create table agentes (
    id bigint primary key references usuarios(id) on delete cascade,
    cnpj varchar(18) not null unique
);

create table empresas (
    id bigint primary key references agentes(id) on delete cascade
);

create table bancos (
    id bigint primary key references agentes(id) on delete cascade
);
