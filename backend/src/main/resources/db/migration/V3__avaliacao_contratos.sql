alter table pedidos add column agente_avaliador_id bigint references agentes(id) on delete set null;
alter table pedidos add column parecer varchar(500);

create table contratos_credito (
    id bigint generated by default as identity primary key,
    banco_id bigint not null references bancos(id),
    valor numeric(12,2) not null,
    taxa_juros numeric(5,2) not null,
    numero_parcelas integer not null
);

create table contratos (
    id bigint generated by default as identity primary key,
    pedido_id bigint not null unique references pedidos(id),
    agente_id bigint not null references agentes(id),
    tipo_proprietario varchar(20) not null,
    data_assinatura date not null,
    contrato_credito_id bigint unique references contratos_credito(id)
);
